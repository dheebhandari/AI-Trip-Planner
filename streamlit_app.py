import streamlit as st
import requests
import datetime

BASE_URL = "https://ai-trip-planner-gwj7.onrender.com"

st.set_page_config(
    page_title="AI Trip Planner",
    page_icon="🌍",
    layout="centered",
    initial_sidebar_state="expanded",
)

st.title("🌍 AI Trip Planner")
st.header("How can I help you plan a trip?")

# Initialize chat history
if "messages" not in st.session_state:
    st.session_state.messages = []

with st.form(key="query_form", clear_on_submit=True):
    user_input = st.text_input(
        "Where would you like to travel?",
        placeholder="e.g. Plan a trip to Goa for 5 days"
    )
    submit_button = st.form_submit_button("Plan My Trip")

if submit_button and user_input.strip():
    try:
        with st.spinner("Planning your trip..."):
            response = requests.post(
                f"{BASE_URL}/query",
                json={"query": user_input},
                timeout=180,
            )

        if response.status_code == 200:
            answer = response.json().get(
                "answer", "No answer returned."
            )

            st.markdown("# 🌍 Your AI Travel Plan")
            st.caption(
                "Generated: "
                + datetime.datetime.now().strftime("%Y-%m-%d at %H:%M")
            )
            st.markdown("---")
            st.markdown(answer)
            st.markdown("---")
            st.caption(
                "AI-generated information may be inaccurate. "
                "Verify prices, opening hours, and travel requirements."
            )
        else:
            st.error(
                f"Backend error ({response.status_code}): "
                f"{response.text}"
            )

    except requests.exceptions.Timeout:
        st.error("The request timed out. Please try again.")
    except requests.exceptions.RequestException as e:
        st.error(f"Could not connect to the backend: {e}")
